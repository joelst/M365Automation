function Get-FriendlyApp {
  param([string]$text, [hashtable]$unused)
  foreach ($prefix in $friendlyBundles.Keys) {
    if ($text -like "$prefix*") { return $friendlyBundles[$prefix] }
  }
  return $null
}

function Test-DescriptorUninformative {
  <#
    Is what remains of the existing name, once the platform is stripped, worth keeping?

    Deliberately conservative. An existing name often carries the INTENT, which no amount of
    content parsing recovers -- 'Block OpenClaw' is worth more than any description of the
    firewall rule that implements it. So a descriptor is only discarded when it is genuinely
    contentless.
  #>
  param([string]$descriptor)

  if ([string]::IsNullOrWhiteSpace($descriptor)) { return $true }
  $words = @($descriptor -split '[^A-Za-z0-9]+' | Where-Object { $_ })
  if (-not $words.Count) { return $true }

  $filler = 'default', 'defaults', 'conf', 'config', 'configuration', 'settings', 'setting',
  'policy', 'policies', 'profile', 'new', 'old', 'test', 'temp', 'prep', 'copy', 'imported',
  'baseline', 'std', 'standard', 'general', 'misc', 'stuff', 'v1', 'v2', 'v3', 'a', 'b', '1', '2', '3'

  $meaningful = @($words | Where-Object { $_.ToLower() -notin $filler -and $_.Length -gt 1 })
  return ($meaningful.Count -eq 0)
}

function Get-DescriptorFromEvidence {
  <#
    Draft a descriptor from what the policy contains, for the cases where its current name
    says nothing. Preference order runs from most authoritative to most speculative.
  #>
  param([object]$Policy, [string]$Category, [string]$TopSettings)

  # 1. Endpoint Security intents name their own template.
  $templateName = "$(Get-PropertyValue -Object $Policy -Name 'templateName')"
  if ($templateName) { return $templateName }

  # 2. Apple payloads: the payload type says what area, the content says which flavour.
  if ($TopSettings) {
    foreach ($key in $payloadDescriptors.Keys) {
      if ($TopSettings -like "*$key*") {
        $descriptor = $payloadDescriptors[$key]

        # Privacy profiles are only distinguishable by the service being granted.
        if ($key -eq 'TCC.configuration-profile-policy') {
          $services = @($tccServices.Keys | Where-Object { $TopSettings -like "*$_*" } | ForEach-Object { $tccServices[$_] } | Sort-Object -Unique)
          if ($services.Count) { $descriptor = ($services -join ' and ') }
        }

        # Name the app it applies to, when there is one.
        $app = $null
        if ($TopSettings -match '\[([^\]]+)\]') {
          foreach ($candidate in ($Matches[1] -split ',\s*')) {
            $app = Get-FriendlyApp -text $candidate.Trim()
            if ($app -and $app -ne 'Apple') { break }
            $app = $null
          }
        }
        if ($app) { return "$app $descriptor" }
        return $descriptor
      }
    }
  }

  # 3. Template family, humanised: 'appQuietTime' -> 'App Quiet Time'.
  $family = "$(Get-PropertyValue -Object $Policy -Name '_templateFamily')"
  if ($family -and $family -ne 'none') {
    $spaced = ($family -creplace '([a-z0-9])([A-Z])', '$1 $2')
    return (Get-Culture).TextInfo.ToTitleCase($spaced.ToLower())
  }

  # 4. Fall back to the first couple of setting names. Drop the OMA-URI tail that
  #    Get-OmaSettingSummary appends for the evidence column -- 'RelaunchNotificationPeriod
  #    (Config/Chrome~Policy~googlechrome/RelaunchNotificationPeriod)' is a useful thing to
  #    read in a spreadsheet and a terrible thing to read in a name. A parenthetical
  #    containing / or ~ is a URI; one without is part of the display name and stays.
  if ($TopSettings) {
    $first = @($TopSettings -split '\s*\|\s*' |
      Where-Object { $_ -and $_ -notmatch '^(Top Level|com\.)' } |
      ForEach-Object { ($_ -replace '\s*\([^)]*[/~][^)]*\)\s*$', '').Trim() } |
      Where-Object { $_ } |
      Select-Object -First 2)
    if ($first.Count) { return ((@($first) -join ', ')) }
  }

  return $null
}

function ConvertTo-CleanDescriptor {
  # Tidy a descriptor kept from the existing name: separators to spaces, collapse repeats.
  # Casing is left alone -- acronyms like ASR, WSL, NLA and LSA must survive.
  param([string]$descriptor)
  if (-not $descriptor) { return $descriptor }
  $clean = $descriptor -replace '[_]+', ' '
  # Even out the spacing around a hyphen used as a SEPARATOR -- one that already has
  # whitespace on at least one side. A hyphen with no space around it is part of a word or an
  # identifier ('in-browser', 'Win11-AutoPatch-FeatureRelease'), and spacing it out corrupts
  # the term: 'in - browser', 'Win11 - AutoPatch - FeatureRelease'.
  $clean = $clean -replace '\s+-\s*|\s*-\s+', ' - '
  $clean = $clean -replace '\s{2,}', ' '
  return $clean.Trim(' ', '-', ':')
}

function ConvertTo-SafeName {
  <#
    Normalise the typography that Word, Outlook and the Intune console quietly introduce.

    A curly apostrophe is not wrong in itself, but a policy name travels through filenames,
    CSVs, scripts and reports, and each hop is a chance for it to be decoded with the wrong
    codepage. 'don't' becoming 'donâ€™t' is the visible symptom; the invisible one is a
    name that no longer matches when something searches for it.

    Only the common offenders are folded to ASCII. Genuinely international text is left
    alone and flagged instead -- silently transliterating someone's language is worse than
    telling them it is there.
  #>
  param([string]$name)
  if (-not $name) { return $name }

  $map = @{
    [char]0x2018 = "'"; [char]0x2019 = "'"      # ' '  curly single quotes
    [char]0x201A = "'"; [char]0x201B = "'"
    [char]0x201C = '"'; [char]0x201D = '"'      # " "  curly double quotes
    [char]0x201E = '"'; [char]0x201F = '"'
    [char]0x2013 = '-'; [char]0x2014 = '-'      # en dash, em dash
    [char]0x2012 = '-'; [char]0x2015 = '-'
    [char]0x2026 = '...'                        # ellipsis
    [char]0x00A0 = ' '                          # non-breaking space
    [char]0x2002 = ' '; [char]0x2003 = ' '; [char]0x2009 = ' '
    [char]0x200B = ''                           # zero-width space
    [char]0x00AD = ''                           # soft hyphen
  }

  $sb = New-Object System.Text.StringBuilder
  foreach ($ch in $name.ToCharArray()) {
    if ($map.ContainsKey($ch)) { [void]$sb.Append($map[$ch]) }
    elseif ([char]::IsControl($ch)) { [void]$sb.Append(' ') }
    else { [void]$sb.Append($ch) }
  }

  $clean = $sb.ToString() -replace '\s{2,}', ' '
  return $clean.Trim()
}

function Get-NameWarnings {
  # Surface what sanitising could not or should not fix, rather than silently mangling it.
  param([string]$name)
  $w = @()
  if (-not $name) { return '' }
  if ($name.Length -gt 120) { $w += "long ($($name.Length) chars)" }
  $nonAscii = @($name.ToCharArray() | Where-Object { [int]$_ -gt 127 } | Sort-Object -Unique)
  if ($nonAscii.Count) { $w += ("non-ASCII: " + (($nonAscii | ForEach-Object { "'$_' U+{0:X4}" -f [int]$_ }) -join ' ')) }
  # Deliberately NOT warning about filename-illegal characters. The chosen separator is a
  # colon, which is illegal in a filename but perfectly valid in a policy name, and the
  # export's own New-SafeFileName already substitutes those when writing files. Warning here
  # would fire on every single row and teach the reader to ignore the column.
  return ($w -join '; ')
}

function Get-TargetLabel {
  <#
    Condense the assignment into something short enough to live inside a name.

    Exclusions are deliberately left out: they are an important detail of the assignment but
    they are not the audience, and 'All devices, EXCLUDE:Exempt Devices,
    EXCLUDE:Exempt Users' does not belong in a policy name. They stay in the
    AssignedTo column.
  #>
  param([string[]]$targets)

  $includes = @($targets | Where-Object { $_ -and $_ -notlike 'EXCLUDE:*' })
  if (-not $includes.Count) { return 'unassigned' }

  $hasAllDevices = $includes -contains 'All devices'
  $hasAllUsers = $includes -contains 'All licensed users'
  if ($hasAllDevices -and $hasAllUsers) { return 'All' }
  if ($hasAllDevices -and $includes.Count -eq 1) { return 'All Devices' }
  if ($hasAllUsers -and $includes.Count -eq 1) { return 'All Users' }

  # Group names carry their own prefix conventions (_Mac Devices, DG-Windows-Devices). Keep
  # them as written -- they are the audience's actual name -- just drop a leading underscore.
  $groups = @($includes | ForEach-Object { ($_ -replace '^_', '') })
  if ($groups.Count -eq 1) { return $groups[0] }
  if ($groups.Count -eq 2) { return ($groups -join ' + ') }
  return ("{0} +{1} more" -f $groups[0], ($groups.Count - 1))
}

function Get-ProposedName {
  <#
    Compose the draft. Keeps whatever meaning the current name already carries and only
    invents a descriptor when there is none to keep.
  #>
  param([object]$Policy, [string]$Category, [string]$CurrentName, [string]$Platform, [string]$TopSettings, [string]$Separator, [string]$TargetLabel)

  # Strip any existing platform token, in whatever spelling.
  $stripped = $CurrentName -replace '^\s*(macOS|macos|MacOS|Mac|Windows|Win1x|Win10|Win11|Win|win|iPadOS|iOS|ios|Android|android)\s*[:\-_ ]\s*', ''
  # Drop a target suffix this tool added on a previous run, so re-running does not stack them.
  # Only the exact label about to be re-appended is removed: a blanket "strip any trailing
  # parenthetical" also eats meaningful ones, and turned 'iOS (18.x)' and 'iOS (26.x)' into
  # the same name.
  if ($TargetLabel) {
    $suffixPattern = '\s*\(\s*' + [regex]::Escape($TargetLabel) + '\s*\)\s*$'
    $stripped = $stripped -replace $suffixPattern, ''
  }
  $stripped = ConvertTo-CleanDescriptor -descriptor $stripped

  # Always work out what the content suggests, whether or not it gets used. It goes in its own
  # column so the two candidates can be compared side by side rather than the tool guessing.
  $derivedRaw = Get-DescriptorFromEvidence -Policy $Policy -Category $Category -TopSettings $TopSettings
  $derived = if ($derivedRaw) { ConvertTo-CleanDescriptor -descriptor $derivedRaw } else { $null }

  # A vendor-generated name describes the download, not the policy: 'MDE (imported) -
  # bluetooth Configuration' is worse than 'Purview DLP Bluetooth Access'. These are the one
  # case where content reliably beats the existing name.
  $isVendorImport = $CurrentName -match '(?i)\(imported\)|^MDE\b|Configuration$'

  $source = 'kept from current name'
  $chosen = $stripped

  if (Test-DescriptorUninformative -descriptor $stripped) {
    if ($derived) { $chosen = $derived; $source = 'derived from content' }
    else { $chosen = ''; $source = 'NEEDS A NAME - no usable evidence' }
  }
  elseif ($isVendorImport -and $derived) {
    $chosen = $derived
    $source = 'derived from content (vendor-generated name)'
  }

  $prefix = if ($Platform) { "$Platform$Separator " } else { '' }
  $suffix = if ($TargetLabel) { " ($TargetLabel)" } else { '' }
  return [pscustomobject]@{
    Name    = ConvertTo-SafeName -name (($prefix + $chosen).Trim() + $suffix)
    Source  = $source
    Derived = $(if ($derived) { ConvertTo-SafeName -name (($prefix + $derived).Trim() + $suffix) } else { '' })
  }
}

