foreach ($typeDir in Get-ChildItem -LiteralPath $datePath -Directory) {
  $category = $typeDir.Name
  foreach ($file in Get-ChildItem -LiteralPath $typeDir.FullName -File) {
    if ($file.Name -notlike '*.json') { continue }
    if ($file.Name -like '*.assignments.json') { continue }
    if ($file.Name -in $nonPolicyFiles) { continue }

    $policy = Get-Content -LiteralPath $file.FullName -Raw | ConvertFrom-Json
    if (-not $policy) { continue }

    $currentName = Get-PropertyValue -Object $policy -Name 'displayName'
    if (-not $currentName) { $currentName = Get-PropertyValue -Object $policy -Name 'name' }
    if (-not $currentName) { continue }

    # Intune's own built-ins are not ours to rename.
    $policyId = "$(Get-PropertyValue -Object $policy -Name 'id')"
    if ($policyId -match '_Default|_WindowsRestore') { continue }

    $assignFile = Join-Path $typeDir.FullName ($file.BaseName + '.assignments.json')
    $targets = @()
    if (Test-Path -LiteralPath $assignFile) {
      $assignments = Get-Content -LiteralPath $assignFile -Raw | ConvertFrom-Json
      foreach ($a in @($assignments)) {
        if ($null -eq $a) { continue }
        if (Get-PropertyValue -Object $a -Name 'allDevices') { $targets += 'All devices' }
        elseif (Get-PropertyValue -Object $a -Name 'allLicensedUsers') { $targets += 'All licensed users' }
        elseif (Get-PropertyValue -Object $a -Name 'groupName') {
          $prefix = if (Get-PropertyValue -Object $a -Name 'isExclusion') { 'EXCLUDE:' } else { '' }
          $targets += "$prefix$(Get-PropertyValue -Object $a -Name 'groupName')"
        }
      }
    }
    $targets = @($targets | Sort-Object -Unique)
    $isAssigned = [bool]$targets.Count
    if ($AssignedOnly -and -not $isAssigned) { continue }

    $platform = Get-DerivedPlatform -Policy $policy -Category $category
    # Last resort only. Get-ProposedName strips the platform token off the front of the current
    # name so the canonical one can be put back -- but when nothing was derived there is nothing
    # to put back, and the token is simply deleted: 'Win10-BitLocker' became 'BitLocker' and
    # 'iOS: Intune Company Portal' became 'Intune Company Portal'. A name that has lost its
    # platform is worse than the one we started with, so where the policy's own data is silent,
    # the existing name is the best evidence available.
    if (-not $platform) { $platform = Get-PlatformFromName -name $currentName }
    if (-not $platform) { $noPlatform++ }

    $topSettings = Get-TopSettings -Policy $policy -Category $category -Definitions $definitions -Limit $topSettingCount
    $targetLabel = if ($IncludeTarget) { Get-TargetLabel -targets $targets } else { $null }
    $draft = Get-ProposedName -Policy $policy -Category $category -CurrentName $currentName `
      -Platform $platform -TopSettings $topSettings -Separator $Separator -TargetLabel $targetLabel

    $rows += [pscustomobject]@{
      ProposedName   = $draft.Name
      CurrentName    = $currentName
      NameSource     = $draft.Source
      NameWarnings   = Get-NameWarnings -name $draft.Name
      DerivedName    = $draft.Derived
      Platform       = $platform
      Category       = $category
      TemplateFamily = "$(Get-PropertyValue -Object $policy -Name '_templateFamily')"
      TemplateName   = "$(Get-PropertyValue -Object $policy -Name 'templateName')"
      Technologies   = "$(Get-PropertyValue -Object $policy -Name 'technologies')"
      TopSettings    = $topSettings
      SettingCount   = "$(Get-PropertyValue -Object $policy -Name 'settingCount')"
      IsAssigned     = $isAssigned
      AssignedTo     = ($targets -join ', ')
      HasDescription = [bool]("$(Get-PropertyValue -Object $policy -Name 'description')".Trim())
      PolicyId       = $policyId
    }
  }
}

