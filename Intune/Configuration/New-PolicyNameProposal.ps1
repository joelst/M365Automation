#region Helpers

function Get-PropertyValue {
  param([object]$Object, [string]$Name)
  if ($null -eq $Object) { return $null }
  if ($Object -is [System.Collections.IDictionary]) {
    if ($Object.Contains($Name)) { return $Object[$Name] }
    return $null
  }
  if ($Object.PSObject.Properties[$Name]) { return $Object.$Name }
  return $null
}

function Get-PlatformFromName {
  <#
    Recover the platform from the leading token of the current name, in canonical spelling.

    Strictly a fallback for when Get-DerivedPlatform finds nothing in the policy's own data:
    a name can lie, whereas @odata.type cannot. It exists because Get-ProposedName strips this
    token unconditionally, so without it the platform is dropped rather than normalised.

    The alternation must mirror the strip regex in Get-ProposedName -- anything stripped there
    and not recognised here is silently lost.
  #>
  param([string]$name)
  if ($name -notmatch '^\s*(macOS|macos|MacOS|Mac|Windows|Win1x|Win10|Win11|Win|win|iPadOS|iOS|ios|Android|android)\s*[:\-_ ]') { return $null }
  switch -Regex ($Matches[1]) {
    '^(?i)(macOS|mac)$'                     { return 'macOS' }
    '^(?i)(windows|win1x|win10|win11|win)$' { return 'Windows' }
    '^(?i)ipados$'                          { return 'iPadOS' }
    '^(?i)ios$'                             { return 'iOS' }
    '^(?i)android$'                         { return 'Android' }
  }
  return $null
}

function Get-DerivedPlatform {
  <#
    Platform from the policy's own data, never from its current name -- the whole point is to
    fix policies whose name says nothing.
  #>
  param([object]$Policy, [string]$Category)

  $canonical = @{ 'windows10' = 'Windows'; 'windows' = 'Windows'; 'windows10andlater' = 'Windows'
    'windows10x' = 'Windows'; 'macos' = 'macOS'; 'ios' = 'iOS'; 'ipados' = 'iPadOS'
    'android' = 'Android'; 'androidenterprise' = 'Android'; 'androidworkprofile' = 'Android'
    'aosp' = 'Android'; 'visionos' = 'visionOS'; 'tvos' = 'tvOS'; 'linux' = 'Linux'
  }

  # 1. Settings Catalog states its platforms outright, sometimes several.
  $platforms = Get-PropertyValue -Object $Policy -Name 'platforms'
  if ($platforms) {
    $parts = @("$platforms" -split '[,\s]+' | Where-Object { $_ -and $_ -ne 'none' -and $_ -ne 'unknownFutureValue' })
    $mapped = @($parts | ForEach-Object { $c = $canonical[$_.ToLowerInvariant()]; if ($c) { $c } else { $_ } } | Sort-Object -Unique)
    if ($mapped.Count) { return ($mapped -join '/') }
  }

  # 2. The @odata.type of a typed profile names its platform.
  $odata = "$(Get-PropertyValue -Object $Policy -Name '@odata.type')"
  if ($odata) {
    if ($odata -match '(?i)macos') { return 'macOS' }
    if ($odata -match '(?i)ipados') { return 'iPadOS' }
    # Match 'ios' at the start of the type name rather than enumerating known type names.
    # '\bios\b' finds no word boundary inside 'iosManagedAppProtection', and the explicit list
    # that backed it up did not include that type -- so the iOS app protection policy derived
    # no platform while its Android sibling, matched by the loose '(?i)android' below, did.
    # Checked after macOS/iPadOS so the more specific platforms win.
    if ($odata -match '(?i)(^|\.)ios') { return 'iOS' }
    if ($odata -match '(?i)android') { return 'Android' }
    if ($odata -match '(?i)windows|win32|sharedPC|editionUpgrade') { return 'Windows' }
  }

  # 3. Some policy types only exist for one platform.
  switch -Wildcard ($Category) {
    'DeviceShellScripts' { return 'macOS' }
    'DeviceManagementScripts' { return 'Windows' }
    'DeviceHealthScripts' { return 'Windows' }
    'Windows*' { return 'Windows' }
    default { return $null }
  }
}

function ConvertFrom-PlistNode {
  # plist XML -> ordered hashtables / arrays / scalars. Parsed structurally rather than by
  # regex because Apple serialises dict entries alphabetically, so 'CodeRequirement' arrives
  # before the 'Identifier' it belongs to and any positional guess attributes it to the wrong
  # app.
  param([System.Xml.XmlNode]$Node)

  switch ($Node.Name) {
    'dict' {
      $h = [ordered]@{}
      $children = @($Node.ChildNodes | Where-Object { $_.NodeType -eq [System.Xml.XmlNodeType]::Element })
      for ($i = 0; $i -lt $children.Count; $i++) {
        if ($children[$i].Name -ne 'key') { continue }
        if ($i + 1 -ge $children.Count) { break }
        $h[$children[$i].InnerText] = ConvertFrom-PlistNode -Node $children[$i + 1]
        $i++
      }
      return $h
    }
    'array' {
      return @($Node.ChildNodes |
          Where-Object { $_.NodeType -eq [System.Xml.XmlNodeType]::Element } |
          ForEach-Object { ConvertFrom-PlistNode -Node $_ })
    }
    'true' { return 'true' }
    'false' { return 'false' }
    'data' { return '<data>' }        # certificates and keys: never surfaced
    default { return $Node.InnerText }
  }
}

function Get-PlistPayloadSummary {
  <#
    Describe what a .mobileconfig actually configures.

    The payload type alone is not enough to tell policies apart: 'MDE (imported) - bluetooth'
    and 'MDE (imported) - fulldisk' are both com.apple.TCC.configuration-profile-policy. What
    distinguishes them is the TCC service being granted and to which app -- so this reaches
    into each payload for the keys that carry meaning, and for the identifiers of whatever
    they apply to.
  #>
  param([Parameter()][AllowNull()][string]$base64Payload, [int]$Limit)

  if (-not $base64Payload) { return $null }

  $boilerplate = 'PayloadUUID', 'PayloadType', 'PayloadVersion', 'PayloadIdentifier',
  'PayloadDisplayName', 'PayloadDescription', 'PayloadOrganization', 'PayloadEnabled',
  'PayloadRemovalDisallowed', 'PayloadScope', 'PayloadContent'
  # Keys whose VALUE names the thing being configured (an app, a helper, a rule target).
  $identityKeys = 'Identifier', 'BundleIdentifier', 'RuleValue', 'PluginBundleID',
  'FilterDataProviderBundleIdentifier', 'TeamIdentifier', 'AllowedTeamIdentifiers'
  # Present in every entry of their payload type, so they distinguish nothing and only crowd
  # out the keys that do.
  $uninformativeKeys = 'CodeRequirement', 'IdentifierType', 'StaticCode', 'Comment',
  'Authorization', 'Services', 'Rules'

  try {
    $xml = [xml][System.Text.Encoding]::UTF8.GetString([System.Convert]::FromBase64String($base64Payload))
  }
  catch { return $null }

  $root = $xml.SelectSingleNode('/plist/dict')
  if ($null -eq $root) { return $null }
  $parsed = ConvertFrom-PlistNode -Node $root

  $payloads = @(if ($parsed.Contains('PayloadContent')) { $parsed['PayloadContent'] } else { @($parsed) })
  $parts = New-Object System.Collections.Generic.List[string]

  foreach ($payload in $payloads) {
    if ($parts.Count -ge $Limit) { break }
    if ($payload -isnot [System.Collections.IDictionary]) { continue }

    $type = "$(if ($payload.Contains('PayloadType')) { $payload['PayloadType'] } else { 'payload' })"
    $shortType = ($type -split '\.' | Select-Object -Last 2) -join '.'

    $settingKeys = New-Object System.Collections.Generic.List[string]
    $identities = New-Object System.Collections.Generic.List[string]

    # Walk this payload, collecting the keys that configure something and the identifiers of
    # whatever is being configured.
    $stack = New-Object System.Collections.Generic.Stack[object]
    $stack.Push($payload)
    $depth = 0
    while ($stack.Count -and $depth -lt 400) {
      $depth++
      $node = $stack.Pop()
      if ($node -is [System.Collections.IDictionary]) {
        foreach ($k in @($node.Keys)) {
          $v = $node[$k]
          if ($k -in $identityKeys) {
            foreach ($iv in @($v)) { if ($iv -is [string] -and $iv -and -not $identities.Contains($iv)) { [void]$identities.Add($iv) } }
            continue
          }
          if ($k -in $boilerplate) { continue }
          # A 10-character all-caps key is an Apple Team ID used as a dictionary key (the
          # extension lists are keyed by vendor), not a setting name.
          $isTeamIdKey = $k -cmatch '^[A-Z0-9]{10}$'
          $keep = ($k -notin $uninformativeKeys) -and (-not $isTeamIdKey)

          if ($v -is [System.Collections.IDictionary] -or ($v -is [System.Collections.IEnumerable] -and $v -isnot [string])) {
            if ($keep -and -not $settingKeys.Contains($k)) { [void]$settingKeys.Add($k) }
            [void]$stack.Push($v)
          }
          elseif ($keep -and -not $settingKeys.Contains($k)) { [void]$settingKeys.Add($k) }
        }
      }
      elseif ($node -is [System.Collections.IEnumerable] -and $node -isnot [string]) {
        foreach ($item in $node) { [void]$stack.Push($item) }
      }
    }

    $detail = (@($settingKeys | Select-Object -First 4) -join ', ')
    if ($identities.Count) { $detail += " [$((@($identities | Select-Object -First 3)) -join ', ')]" }
    [void]$parts.Add(("{0}: {1}" -f $shortType, $detail.Trim()))
  }

  return (@($parts) -join '  |  ')
}

function Get-OmaSettingSummary {
  # Windows custom profiles carry OMA-URI settings; the URI tail is what identifies them.
  param([Parameter()][AllowNull()][object]$omaSettings, [int]$Limit)

  $out = New-Object System.Collections.Generic.List[string]
  foreach ($o in @($omaSettings)) {
    if ($out.Count -ge $Limit) { break }
    if ($null -eq $o) { continue }
    $name = Get-PropertyValue -Object $o -Name 'displayName'
    $uri = Get-PropertyValue -Object $o -Name 'omaUri'
    $tail = if ($uri) { ($uri -split '/' | Where-Object { $_ } | Select-Object -Last 3) -join '/' } else { $null }
    if ($name -and $tail) { [void]$out.Add("$name ($tail)") }
    elseif ($name) { [void]$out.Add("$name") }
    elseif ($tail) { [void]$out.Add("$tail") }
  }
  if (-not $out.Count) { return $null }
  return (@($out) -join ' | ')
}

function Get-TopSettings {
  <#
    A handful of human-readable setting names -- the single most useful column, because it is
    what tells you a policy called 'Default-Conf-Settings' is really about Storage Sense and
    MDM-wins-over-GP.
  #>
  param([object]$Policy, [string]$Category, [object]$Definitions, [int]$Limit)

  $out = New-Object System.Collections.Generic.List[string]

  # Settings Catalog: resolve each settingDefinitionId to its display name.
  foreach ($s in @(Get-PropertyValue -Object $Policy -Name 'settings')) {
    if ($out.Count -ge $Limit) { break }
    $instance = Get-PropertyValue -Object $s -Name 'settingInstance'
    $defId = Get-PropertyValue -Object $instance -Name 'settingDefinitionId'
    if (-not $defId) {
      # Endpoint Security intents carry definitionId + displayName directly.
      $name = Get-PropertyValue -Object $s -Name 'displayName'
      if ($name) { [void]$out.Add("$name") }
      continue
    }
    $display = $null
    if ($null -ne $Definitions) { $display = Get-PropertyValue -Object (Get-PropertyValue -Object $Definitions -Name $defId) -Name 'displayName' }
    if ($display) { [void]$out.Add("$display") }
    else { [void]$out.Add((($defId -split '_' | Select-Object -Last 2) -join '/')) }
  }

  # Administrative templates: the definition display name is the setting.
  foreach ($dv in @(Get-PropertyValue -Object $Policy -Name 'definitionValues')) {
    if ($out.Count -ge $Limit) { break }
    $def = Get-PropertyValue -Object $dv -Name 'definition'
    $name = Get-PropertyValue -Object $def -Name 'displayName'
    if ($name) { [void]$out.Add("$name") }
  }

  # Windows custom profiles: OMA-URI settings.
  if ($out.Count -lt $Limit) {
    $oma = Get-OmaSettingSummary -omaSettings (Get-PropertyValue -Object $Policy -Name 'omaSettings') -Limit $Limit
    if ($oma) { [void]$out.Add($oma) }
  }

  # Apple custom profiles: parse the .mobileconfig itself. The payload TYPE alone cannot tell
  # a Bluetooth TCC grant from a Full Disk Access one -- both are
  # com.apple.TCC.configuration-profile-policy -- so the plist is read properly.
  if ($out.Count -lt $Limit) {
    $plist = Get-PlistPayloadSummary -base64Payload (Get-PropertyValue -Object $Policy -Name 'payload') -Limit $Limit
    if ($plist) { [void]$out.Add($plist) }
    else {
      # Unparseable payload: fall back to whatever payload types the export recorded.
      foreach ($t in @(Get-PropertyValue -Object $Policy -Name '_payloadTypes')) {
        if ($out.Count -ge $Limit) { break }
        if ($t) { [void]$out.Add("$t") }
      }
    }
  }

  # Typed profiles and compliance policies keep settings as top-level properties. Skip
  # metadata and anything left at its default, so only configured settings surface.
  if ($out.Count -lt $Limit) {
    $skip = 'id', 'displayName', 'name', 'description', 'createdDateTime', 'lastModifiedDateTime',
    'version', 'roleScopeTagIds', 'supportsScopeTags', 'isAssigned', 'platforms', 'technologies',
    'settingCount', 'creationSource', 'priorityMetaData', 'templateReference', 'deviceManagementApplicabilityRuleOsEdition',
    'deviceManagementApplicabilityRuleOsVersion', 'deviceManagementApplicabilityRuleDeviceMode',
    'payload', 'payloadName', 'payloadFileName', 'deploymentChannel', 'scheduledActionsForRule',
    'settings', 'definitionValues', 'omaSettings', 'assignments'
    $defaults = @($null, $false, 0, '', 'notConfigured', 'deviceDefault', 'unavailable')

    foreach ($prop in $Policy.PSObject.Properties) {
      if ($out.Count -ge $Limit) { break }
      if ($prop.Name -in $skip -or $prop.Name -like '_*' -or $prop.Name -like '@*') { continue }
      if ($prop.Value -in $defaults) { continue }
      if ($prop.Value -is [System.Collections.IEnumerable] -and $prop.Value -isnot [string]) { continue }
      # camelCase -> spaced, so the column reads like English
      [void]$out.Add(($prop.Name -creplace '([a-z0-9])([A-Z])', '$1 $2'))
    }
  }

  return (@($out) -join ' | ')
}

