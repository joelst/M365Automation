#region Disambiguate collisions

<#
  Two policies can legitimately deserve the same description. A remediation script called
  'ASR Rules' and an Endpoint Security policy called 'Windows ASR Rules' really are both
  about ASR, and both drafts land on 'Windows: ASR Rules (All Devices)'. Intune would accept
  the duplicate, a human reading a list could not tell the two apart, and Invoke-PolicyRename
  refuses the entire sheet over it.

  The fix is deliberately narrow: add a token naming what KIND of object it is, to the
  colliding rows only. Applying it to every row would push a fourth slot into the
  '<Platform>: <description> (<audience>)' convention for ~98 policies to solve a problem
  that affects two -- and would give the platform-strip regex in Get-ProposedName a new token
  it does not know how to strip on the next run.
#>

$kindLabels = @{
  DeviceHealthScripts          = 'Remediation'
  DeviceManagementScripts      = 'Script'
  DeviceShellScripts           = 'Shell Script'
  CompliancePolicies           = 'Compliance'
  WindowsFeatureUpdateProfiles = 'Feature Update'
  WindowsDriverUpdateProfiles  = 'Driver Update'
  AppProtectionPolicies        = 'App Protection'
  AppConfigurationPolicies     = 'App Config'
  EnrollmentConfigurations     = 'Enrollment'
  GroupPolicyConfigurations    = 'ADMX'
}

function Add-KindToken {
  # Insert the kind just after the platform prefix, so the name still reads
  # '<Platform><sep> <kind> - <description> (<audience>)'.
  param([string]$name, [string]$platform, [string]$token)

  if (-not $name -or -not $token) { return $name }
  # Idempotent: a policy already called 'Remediation - ...' does not need it twice.
  if ($name -match ('(?i)(^|[:\-]\s+)' + [regex]::Escape($token) + '\b')) { return $name }

  if ($platform) {
    $prefixPattern = '^(' + [regex]::Escape($platform) + '\s*[:\-]?\s*)'
    if ($name -match $prefixPattern) { return ($name -replace $prefixPattern, ('${1}' + $token + ' - ')) }
  }
  return "$token - $name"
}

$collisionCount = 0
$unresolvedCollisions = New-Object System.Collections.Generic.List[string]

foreach ($group in @($rows | Where-Object { $_.ProposedName } |
                     Group-Object { $_.ProposedName.ToLowerInvariant() } |
                     Where-Object { $_.Count -gt 1 })) {

  foreach ($row in $group.Group) {
    $token = $kindLabels[$row.Category]
    if (-not $token) { continue }   # configuration policies are the unmarked default
    $row.ProposedName = Add-KindToken -name $row.ProposedName -platform $row.Platform -token $token
    if ($row.DerivedName) { $row.DerivedName = Add-KindToken -name $row.DerivedName -platform $row.Platform -token $token }
    $row.NameWarnings = Get-NameWarnings -name $row.ProposedName
  }

  # Did that actually separate them? If two policies of the SAME kind still collide, no token
  # can tell them apart -- that is a real decision for a human, so say so rather than inventing
  # a suffix that makes the sheet pass while leaving two indistinguishable names behind.
  $stillColliding = @($group.Group | Group-Object { $_.ProposedName.ToLowerInvariant() } | Where-Object { $_.Count -gt 1 })
  if ($stillColliding) {
    foreach ($dupe in $stillColliding) {
      [void]$unresolvedCollisions.Add("$($dupe.Name) -- $($dupe.Count) policies")
      foreach ($row in $dupe.Group) {
        $row.NameWarnings = (@($row.NameWarnings, 'DUPLICATE NAME - needs a human') | Where-Object { $_ }) -join '; '
      }
    }
  } else {
    $collisionCount++
  }
}

