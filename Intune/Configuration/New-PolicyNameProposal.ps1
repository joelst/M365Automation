<#
.SYNOPSIS
Builds an evidence sheet for renaming Intune policies: what each policy actually contains,
next to its current name, with the mechanical half of a new name pre-filled.

.DESCRIPTION
Read-only. Reads an export produced by Export-DeviceConfigurations.ps1 -- it never contacts
Graph, so it needs no authentication and cannot change anything.

The goal is not to invent names. Content tells you a policy's mechanism but not its intent:
'A365 - Block OpenClaw' contains a firewall rule and two WSL settings, and a name derived
from that content would be strictly worse than the one it has. What a tool CAN do is remove
the archaeology -- surface platform, template family, technologies and the actual setting
display names -- so that naming a policy takes seconds instead of clicking through settings.

So each row arrives with a drafted name and the evidence behind it:
  - ProposedName -- a full drafted name: <Platform><sep> <description> (<audience>)
  - NameSource   -- whether the description was kept from the current name or derived from
                    the policy's contents
  - DerivedName  -- the content-derived alternative, always populated, so the two candidates
                    can be compared where they differ
  - the evidence itself: platform, template family, technologies, the actual setting names,
    setting count and assignment

The description half is kept from the existing name wherever that name carries meaning --
'Block OpenClaw' says why a policy exists in a way no amount of setting parsing recovers. It
is only replaced when the current name is contentless ('Default-Conf-Settings') or was
generated by a vendor ('MDE (imported) - fulldisk Configuration').

Review and correct ProposedName, then Invoke-PolicyRename.ps1 applies the sheet.

IMPORTANT: every row arrives with a name filled in, so every row is actionable by default.
BLANK the ProposedName cell for any policy you do not want renamed.

.PARAMETER ExportRoot
Root of the exports tree. Defaults to .\exports.

.PARAMETER TenantId
Tenant folder to read. Defaults to the first one found.

.PARAMETER ExportDate
Date folder (yyyy-MM-dd). Defaults to the most recent.

.PARAMETER OutputPath
CSV to write. Defaults to policy-name-proposal.csv in the export date folder.

.PARAMETER AssignedOnly
Only include policies that reach at least one device or user. Unassigned policies are usually
candidates for deletion rather than renaming.

.PARAMETER Separator
Character between platform and description in the pre-filled name. Default ':'.

.EXAMPLE
./New-PolicyNameProposal.ps1

Writes policy-name-proposal.csv alongside the export.

.EXAMPLE
./New-PolicyNameProposal.ps1 -AssignedOnly

Only the policies that are actually doing something.

.NOTES
No Graph permissions required.

Platform is derived from the policy's own data -- platforms, @odata.type, or the policy type
(shell scripts are macOS, health scripts are Windows) -- not from the existing name. On the
current tenant that resolves 101 of the 105 policies that have no platform prefix at all.
#>

[CmdletBinding()]
param(
  [Parameter()]
  [ValidateNotNullOrEmpty()]
  [string]$ExportRoot = (Join-Path $PSScriptRoot 'exports'),

  [Parameter()]
  [ValidateNotNullOrEmpty()]
  [string]$TenantId,

  [Parameter()]
  [ValidatePattern('^\d{4}-\d{2}-\d{2}$')]
  [string]$ExportDate,

  [Parameter()]
  [ValidateNotNullOrEmpty()]
  [string]$OutputPath,

  [Parameter()]
  [switch]$AssignedOnly,

  [Parameter()]
  [ValidateNotNullOrEmpty()]
  [string]$Separator = ':',

  # Append the intended audience, e.g. 'macOS: Defender Full Disk Access (All Macs)'.
  # Exclusions are left out -- they are assignment detail, not audience.
  # Pass -IncludeTarget:$false to leave it out entirely; see the note in .NOTES about drift.
  [Parameter()]
  [bool]$IncludeTarget = $true
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

